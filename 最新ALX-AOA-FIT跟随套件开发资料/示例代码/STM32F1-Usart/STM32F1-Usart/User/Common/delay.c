#include  "delay.h"


/*
 *******************************************************************************
 *    移植时，需根据单片机时钟及位数调整参数
 *******************************************************************************
 */

void SoftDelayXms(u32 nXms)
{
	u32 i,j;

	for(i=0;i<nXms;i++)
	{
		j=7200;
		while(j--);
	}
}
/*
 *******************************************************************************
 *    
 *******************************************************************************
 */
void SoftDelayXus(u32 nXus)
{
    for(;nXus;nXus--);
}
/*
 *******************************************************************************
 *    
 *******************************************************************************
 */
void Delay(u32 nCount)
{
  for(; nCount != 0; nCount--);
}
